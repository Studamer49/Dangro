/** Every entry across all categories, in display order. */
export const ALL_EMOJI: EmojiEntry[] = EMOJI_CATEGORIES.flatMap((c) => c.emojis);

const BY_NAME = new Map<string, EmojiEntry>();
for (const entry of ALL_EMOJI) {
  if (!BY_NAME.has(entry.n)) BY_NAME.set(entry.n, entry);
}

/** Resolves a `;;name;;` shortcode to its glyph, or null. */
export function emojiByName(name: string): string | null {
  return BY_NAME.get(name.trim().toLowerCase())?.e ?? null;
}

/** Name search across glyph names and their aliases. */
export function searchEmojis(query: string): EmojiEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return ALL_EMOJI.filter(
    (entry) =>
      entry.n.includes(q) ||
      (entry.k ?? []).some((word) => word.includes(q))
  );
}

export const EMOJI_SHORTCODE_RE = /;;([A-Za-z0-9_+-]+);;/g;
export function replaceEmojiShortcodes(text: string): string {
  return text.replace(EMOJI_SHORTCODE_RE, (match, name) => emojiByName(name) ?? match);
}
